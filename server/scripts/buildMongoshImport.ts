/**
 * Turn a price list into a standalone mongosh script, for adding products to a
 * company without deploying the API: it needs only mongosh and a database login.
 *
 *   npx ts-node scripts/buildMongoshImport.ts scripts/data/duraflow-pprc-2026-09-08.json scripts/mongosh/import-duraflow-pprc.js
 *
 * The generated script mirrors what the app stores (tenantId, timestamps,
 * defaults). Products whose barcode the company already has are not added
 * again, but are renamed if their name is in an older format. It only writes
 * when run with APPLY set (see its header).
 */
import fs from 'fs';
import path from 'path';
import { productsFrom, type PriceList } from './lib/priceList';

const [input, output] = process.argv.slice(2);
if (!input || !output) throw new Error('Usage: buildMongoshImport.ts <price-list.json> <output.js>');

const list = JSON.parse(fs.readFileSync(path.resolve(input), 'utf8')) as PriceList;
const products = productsFrom(list);

const script = `// Generated by server/scripts/buildMongoshImport.ts from ${path.basename(input)} (${list.source}).
// Adds ${products.length} products in category "${list.category}" to ONE company.
//
// Dry run (writes nothing):
//   mongosh "<connection string>" --eval 'var TENANT = "haji-nawaz-sons-sanitary-store"' --file ${path.basename(output)}
// Import:
//   mongosh "<connection string>" --eval 'var TENANT = "haji-nawaz-sons-sanitary-store"; var APPLY = true' --file ${path.basename(output)}
//
// Safe to re-run: products the company already has (same barcode) are not added again;
// any still named in an older format are renamed to "<size> <product> <company>".

const CATEGORY = ${JSON.stringify(list.category)};
const PRODUCTS = ${JSON.stringify(products, null, 0).replace(/},{/g, '},\n  {')};

if (typeof TENANT === 'undefined' || !TENANT) throw new Error('Set TENANT to the company slug, e.g. --eval \\'var TENANT = "my-shop"\\'');
const apply = typeof APPLY !== 'undefined' && APPLY === true;

const tenant = db.tenants.findOne({ slug: String(TENANT).toLowerCase() });
if (!tenant) throw new Error('No company found with slug "' + TENANT + '"');

// Products already added from this list, by barcode (which never changes).
const existing = new Map(
  db.products.find({ tenantId: tenant._id, barcode: { $in: PRODUCTS.map((p) => p.barcode) } }, { barcode: 1, name: 1 }).toArray().map((p) => [p.barcode, p])
);
const toAdd = PRODUCTS.filter((p) => !existing.has(p.barcode));
// Those named in an older format are renamed to the current one.
const toRename = PRODUCTS.filter((p) => existing.has(p.barcode) && existing.get(p.barcode).name !== p.name);
const hasCategory = Boolean(db.categories.findOne({ tenantId: tenant._id, name: CATEGORY }));

print((apply ? 'IMPORTING into ' : 'DRY RUN (nothing written) for ') + tenant.name + ' [' + tenant.slug + ']');
print('In list: ' + PRODUCTS.length + ' | already there: ' + existing.size + ' | to add: ' + toAdd.length + ' | to rename: ' + toRename.length + ' | category "' + CATEGORY + '" ' + (hasCategory ? 'exists' : 'will be created'));
toAdd.forEach((p) => print('  ' + (apply ? 'add ' : 'would add ') + p.name + '  [' + p.barcode + ']  ' + p.price));
toRename.forEach((p) => print('  ' + (apply ? 'rename ' : 'would rename ') + existing.get(p.barcode).name + '  ->  ' + p.name));

if (apply) {
  const now = new Date();
  if (!hasCategory) {
    db.categories.insertOne({ name: CATEGORY, items: [], vatRate: 0, vatType: 'exclusive', tenantId: tenant._id, createdAt: now, updatedAt: now, __v: 0 });
  }
  if (toAdd.length) {
    const result = db.products.insertMany(
      toAdd.map((p) => Object.assign({}, p, { drs: 0, image: null, tenantId: tenant._id, createdAt: now, updatedAt: now, __v: 0 })),
      { ordered: false }
    );
    print('Added ' + Object.keys(result.insertedIds).length + ' products.');
  }
  if (toRename.length) {
    const renamed = db.products.bulkWrite(
      toRename.map((p) => ({ updateOne: { filter: { _id: existing.get(p.barcode)._id, tenantId: tenant._id }, update: { $set: { name: p.name, updatedAt: now } } } })),
      { ordered: false }
    );
    print('Renamed ' + renamed.modifiedCount + ' products.');
  }
  print('Done. Tills pick the new products up on their next Pull or Sync.');
}
`;

fs.mkdirSync(path.dirname(path.resolve(output)), { recursive: true });
fs.writeFileSync(path.resolve(output), script);
console.log(`Wrote ${products.length} products to ${output}`);
